// Orders belonging to current sales' customers
function makeOrder(
  id: number,
  customerId: number,
  customerName: string,
  status: Order['status'],
  items: { product_id: number; product_name: string; sku: string; unit: string; quantity: number; unit_price: number }[],
  payment: Order['payment_method'],
  daysAgo: number,
  remark?: string,
): Order {
  const total = items.reduce((s, it) => s + it.unit_price * it.quantity, 0)
  return {
    id: `ORD${String(id).padStart(6, '0')}`,
    customer_id: customerId,
    customer_name: customerName,
    sales_id: 1,
    sales_name: '张推广',
    status,
    payment_method: payment,
    total_amount: Number(total.toFixed(2)),
    paid_amount: payment === 'online' || ['completed', 'shipped'].includes(status) ? total : 0,
    items: items.map((it) => ({ ...it, subtotal: Number((it.unit_price * it.quantity).toFixed(2)) })),
    remark,
    created_at: dayjs().subtract(daysAgo, 'day').format('YYYY-MM-DD HH:mm:ss'),
    audited_at: status !== 'pending_audit' ? dayjs().subtract(daysAgo, 'day').add(1, 'hour').format('YYYY-MM-DD HH:mm:ss') : undefined,
    shipped_at: ['shipped', 'completed'].includes(status) ? dayjs().subtract(daysAgo - 1, 'day').format('YYYY-MM-DD HH:mm:ss') : undefined,
    completed_at: status === 'completed' ? dayjs().subtract(daysAgo - 2, 'day').format('YYYY-MM-DD HH:mm:ss') : undefined,
    delivery_address: customers.find((c) => c.id === customerId)?.address,
  }
}

